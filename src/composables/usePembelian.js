import { ref } from 'vue'
import { supabase } from './useSupabase'

export function usePembelian() {
  const pembelian = ref([])
  const loading = ref(false)
  const error = ref(null)

  async function getAllPembelian(filters = {}) {
    loading.value = true
    error.value = null
    try {
      let query = supabase
        .from('pembelian')
        .select(`
          *,
          produk:produk_id(*),
          suplier:suplier_id(*)
        `)
        .order('tanggal_transaksi', { ascending: false })
        .order('created_at', { ascending: false })

      if (filters.startDate) {
        query = query.gte('tanggal_transaksi', filters.startDate)
      }
      if (filters.endDate) {
        query = query.lte('tanggal_transaksi', filters.endDate)
      }

      const { data, error: fetchError } = await query

      if (fetchError) throw fetchError

      let result = data || []

      // Client-side search filter
      if (filters.search) {
        const searchLower = filters.search.toLowerCase()
        result = result.filter(item => 
          item.produk?.nama_produk.toLowerCase().includes(searchLower) ||
          item.suplier?.nama_suplier.toLowerCase().includes(searchLower)
        )
      }

      pembelian.value = result
      return result
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  async function createPembelian(formData) {
    loading.value = true
    error.value = null
    try {
      const { data, error: insertError } = await supabase
        .from('pembelian')
        .insert({
          tanggal_transaksi: formData.tanggal_transaksi,
          produk_id: formData.produk_id,
          suplier_id: formData.suplier_id,
          waktu_beli: formData.waktu_beli,
          quantity: formData.quantity,
          harga_beli: formData.harga_beli,
          keterangan: formData.keterangan || null,
          no_transaksi: '' // Will be auto-generated by trigger
        })
        .select()
        .single()

      if (insertError) throw insertError
      return data
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  async function updatePembelian(id, formData) {
    loading.value = true
    error.value = null
    try {
      const { error: updateError } = await supabase
        .from('pembelian')
        .update({
          tanggal_transaksi: formData.tanggal_transaksi,
          produk_id: formData.produk_id,
          suplier_id: formData.suplier_id,
          waktu_beli: formData.waktu_beli,
          quantity: formData.quantity,
          harga_beli: formData.harga_beli,
          keterangan: formData.keterangan || null
        })
        .eq('id', id)

      if (updateError) throw updateError
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  async function deletePembelian(id) {
    loading.value = true
    error.value = null
    try {
      const { error: deleteError } = await supabase
        .from('pembelian')
        .delete()
        .eq('id', id)

      if (deleteError) throw deleteError
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  return {
    pembelian,
    loading,
    error,
    getAllPembelian,
    createPembelian,
    updatePembelian,
    deletePembelian
  }
}