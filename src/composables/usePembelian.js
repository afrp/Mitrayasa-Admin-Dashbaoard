// composables/usePembelian.js (UPDATED with payment support)
import { ref } from 'vue'
import { supabase } from './useSupabase'

export function usePembelian() {
  const pembelian = ref([])
  const loading = ref(false)
  const error = ref(null)

  async function getAllPembelian(filters = {}) {
    loading.value = true
    error.value = null
    try {
      let query = supabase
        .from('pembelian')
        .select(`
          *,
          produk:produk_id(*),
          suplier:suplier_id(*)
        `)
        .order('tanggal_transaksi', { ascending: false })
        .order('created_at', { ascending: false })

      if (filters.startDate) {
        query = query.gte('tanggal_transaksi', filters.startDate)
      }
      if (filters.endDate) {
        query = query.lte('tanggal_transaksi', filters.endDate)
      }
      if (filters.status_pembayaran) {
        query = query.eq('status_pembayaran', filters.status_pembayaran)
      }

      const { data, error: fetchError } = await query

      if (fetchError) throw fetchError

      let result = data || []

      // Client-side search filter
      if (filters.search) {
        const searchLower = filters.search.toLowerCase()
        result = result.filter(item => 
          item.produk?.nama_produk.toLowerCase().includes(searchLower) ||
          item.suplier?.nama_suplier.toLowerCase().includes(searchLower)
        )
      }

      pembelian.value = result
      return result
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  async function getPembelianLazy(filters = {}, { page = 0, rows = 10, sortField, sortOrder }) {
    loading.value = true
    error.value = null
    try {
      const from = page * rows
      const to = from + rows - 1

      let query = supabase
        .from('pembelian')
        .select(`
          *,
          produk:produk_id(*),
          suplier:suplier_id(*)
        `, { count: 'exact' })

      // Sorting
      if (sortField) {
        query = query.order(sortField, { ascending: sortOrder === 1 })
      } else {
        query = query.order('tanggal_transaksi', { ascending: false })
          .order('created_at', { ascending: false })
      }

      // Filters
      if (filters.startDate) {
        query = query.gte('tanggal_transaksi', filters.startDate)
      }
      if (filters.endDate) {
        query = query.lte('tanggal_transaksi', filters.endDate)
      }
      if (filters.status_pembayaran) {
        query = query.eq('status_pembayaran', filters.status_pembayaran)
      }

      const { data, count, error: fetchError } = await query.range(from, to)

      if (fetchError) throw fetchError

      let resultData = data || []
      if (filters.search) {
        const s = filters.search.toLowerCase()
        resultData = resultData.filter(item =>
          item.produk?.nama_produk.toLowerCase().includes(s) ||
          item.suplier?.nama_suplier.toLowerCase().includes(s) ||
          item.keterangan?.toLowerCase().includes(s) ||
          item.no_transaksi?.toLowerCase().includes(s)
        )
      }

      return {
        data: resultData,
        totalRecords: count || 0
      }
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  async function createPembelian(formData) {
    loading.value = true
    error.value = null
    try {
      const { data, error: insertError } = await supabase
        .from('pembelian')
        .insert({
          tanggal_transaksi: formData.tanggal_transaksi,
          produk_id: formData.produk_id,
          suplier_id: formData.suplier_id,
          waktu_beli: formData.waktu_beli,
          quantity: formData.quantity,
          harga_beli: formData.harga_beli,
          keterangan: formData.keterangan || null,
          // Payment fields
          status_pembayaran: formData.status_pembayaran || 'Belum Lunas',
          // Only set jumlah_dibayar to total if status is 'Lunas', otherwise use 0 or user-provided value
          jumlah_dibayar: formData.status_pembayaran === 'Lunas' 
            ? parseFloat(formData.quantity * formData.harga_beli)
            : parseFloat(formData.jumlah_dibayar || 0),
          tanggal_jatuh_tempo: formData.tanggal_jatuh_tempo || null,
          keterangan_pembayaran: formData.keterangan_pembayaran || null
          // no_transaksi: omitted, will be auto-generated by DB
        })
        .select(`
          *,
          produk:produk_id(*),
          suplier:suplier_id(*)
        `)
        .single()

      if (insertError) throw insertError
      return data
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  async function updatePembelian(id, formData) {
    loading.value = true
    error.value = null
    try {
      const { error: updateError } = await supabase
        .from('pembelian')
        .update({
          tanggal_transaksi: formData.tanggal_transaksi,
          produk_id: formData.produk_id,
          suplier_id: formData.suplier_id,
          waktu_beli: formData.waktu_beli,
          quantity: formData.quantity,
          harga_beli: formData.harga_beli,
          keterangan: formData.keterangan || null,
          // Payment fields
          status_pembayaran: formData.status_pembayaran,
          // Only set jumlah_dibayar to total if status is 'Lunas', otherwise use provided value
          jumlah_dibayar: formData.status_pembayaran === 'Lunas'
            ? parseFloat(formData.quantity * formData.harga_beli)
            : parseFloat(formData.jumlah_dibayar || 0),
          tanggal_jatuh_tempo: formData.tanggal_jatuh_tempo || null,
          keterangan_pembayaran: formData.keterangan_pembayaran || null
        })
        .eq('id', id)

      if (updateError) throw updateError
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  async function deletePembelian(id) {
    loading.value = true
    error.value = null
    try {
      const { error: deleteError } = await supabase
        .from('pembelian')
        .delete()
        .eq('id', id)

      if (deleteError) throw deleteError
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  async function getPembelianById(id) {
    loading.value = true
    error.value = null
    try {
      const { data, error: fetchError } = await supabase
        .from('pembelian')
        .select(`
          *,
          produk:produk_id(*),
          suplier:suplier_id(*)
        `)
        .eq('id', id)
        .single()

      if (fetchError) throw fetchError
      return data
    } catch (e) {
      error.value = e.message
      throw e
    } finally {
      loading.value = false
    }
  }

  return {
    pembelian,
    loading,
    error,
    getAllPembelian,
    getPembelianLazy,
    createPembelian,
    updatePembelian,
    deletePembelian,
    getPembelianById
  }
}